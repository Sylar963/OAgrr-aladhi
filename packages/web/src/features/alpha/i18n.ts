export type AlphaKey = keyof typeof alphaMessages.en;

export const VERTICAL_LABEL_KEYS: Record<VerticalKind, AlphaKey> = {
  'call-credit': 'verticalCallCredit',
  'put-credit': 'verticalPutCredit',
  'call-debit': 'verticalCallDebit',
  'put-debit': 'verticalPutDebit',
};

const REJECTION_KEYS: Record<string, AlphaKey> = {
  'Missing buy ask / sell bid': 'rejMissingBidAsk',
  'Unknown entry fees': 'rejUnknownFees',
  'Stale or missing timestamp': 'rejStale',
  'Leg timestamps out of sync': 'rejSkew',
  'Quantity below minimum or off step': 'rejQuantity',
  'Order value below venue minimum': 'rejMinNotional',
  'Insufficient displayed size': 'rejDisplayedSize',
  'No positive payoff after costs': 'rejNoPayoff',
  'Missing execution metadata / fees': 'rejMissingExecution',
  'Inverse settlement needs separate risk model': 'rejInverse',
  'Missing inverse conversion price': 'rejInversePrice',
  'Settlement mismatch': 'rejSettlement',
  'Leg expiry times differ': 'rejExpiryDiffer',
  'Crossed leg quote': 'rejCrossed',
  'Enable a second venue to route across venues': 'rejSingleVenue',
  'Unknown size rules': 'rejSizeRules',
  'Enter valid sizing and an unexpired expiry': 'rejInvalidInput',
  'No two strikes available on this venue': 'rejNoTwoStrikes',
  'Same-venue route is as good or better': 'rejNotBetter',
  'No strikes quoted on this venue': 'rejNoStrikes',
};

export function humanizeRejection(reason: string, t: AlphaT): string {
  const key = REJECTION_KEYS[reason];
  return key ? t(key) : reason;
}
